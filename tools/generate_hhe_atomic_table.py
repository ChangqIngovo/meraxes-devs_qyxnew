#!/usr/bin/env python3
"""Generate the native closed H/He coefficients from the frozen research kernel.

Only regeneration requires NumPy/SciPy. The committed C table needs no Python at
runtime. Positive linear interpolation of all rates/emission moments together
preserves the recombination energy identity at every interpolated temperature.
"""
from pathlib import Path
import argparse
import hashlib
import sys
import numpy as np
from scipy.special import erfcx

ROOT = Path(__file__).resolve().parents[1]
REFERENCE = ROOT / "tools/hhe_reference"
sys.path.insert(0, str(REFERENCE / "atomic"))
from closed_hhe import kernel, HEI_BANDS
from atomic_hhe import sigma
sys.path.insert(0, str(REFERENCE / "thermal"))
from thermal_closure import collisional_ionization_coefficients


def frequency_grid():
    nodes = []
    for lo, hi in [(13.6, 24.59), (24.59, 54.4), (54.4, 120.), (120., 1000.)]:
        upper = np.nextafter(hi, 0.) if hi in (24.59, 54.4) else hi
        nodes.extend(np.geomspace(lo, upper, 6))
    return np.unique(np.r_[nodes, 18., 20.616, 21.2, 35., 40.8, 70.])


GRID = np.r_[frequency_grid(), 21.2, 40.8]
KIND = np.r_[np.zeros(len(GRID)-2, dtype=int), 1, 2]


def project(energies, counts, kinds):
    """Positive count/energy conserving projection without threshold crossing."""
    result = np.zeros(len(GRID))
    continuum = GRID[:-2]
    for e, number, kind in zip(energies, counts, kinds):
        if number == 0:
            continue
        if kind:
            index = len(continuum) + int(kind) - 1
            assert e == GRID[index]
            result[index] += number
            continue
        if not continuum[0] <= e <= continuum[-1]:
            raise ValueError("Emission outside fixed frequency grid")
        upper = min(int(np.searchsorted(continuum, e, side="right")), len(continuum)-1)
        lower = max(upper-1, 0)
        width = continuum[upper]-continuum[lower]
        fraction = (e-continuum[lower])/width if width else 0.
        result[lower] += number*(1-fraction)
        result[upper] += number*fraction
    return result


def line_sigma(T):
    c = 2.99792458e10
    re = 2.8179403262e-13
    hei_A = 1.7989e9
    hei_f = hei_A*(584.33436e-8)**2*3/(8*np.pi**2*re*c)
    frequency = np.array([21.2, 40.8])*1.602176634e-12/6.62607015e-27
    dnu = frequency*np.sqrt(2*1.380649e-16*T/(4.002602*1.66053906660e-24))/c
    damping = np.array([hei_A/(1-1/915.), 16*6.26485e8])/(4*np.pi*dnu)
    return np.sqrt(np.pi)*re*c*np.array([hei_f, 8192/19683.])/dnu*erfcx(damping)


def coefficients(T):
    k = kernel(T, ground_order=2)
    emission = np.stack([project(k["energies_eV"],
        np.where(k["group_parent"] == parent, k["photon_alpha_cm3_s"], 0.),
        k["group_kind"]) for parent in range(3)])
    down = k["alpha_down_cm3_s"]
    cooling = k["captured_cooling_alpha_eV_cm3_s"]
    inactive = k["low_energy_escape_alpha_eV_cm3_s"]
    np.testing.assert_allclose(emission @ GRID + inactive,
        down*np.array([13.6, 24.59, 54.4])+cooling, rtol=8e-15, atol=0.)
    ev = 1.602176634e-12
    excitation = 7.5e-19*np.exp(-.75*157807./T)/(1+np.sqrt(T/1e5))/ev
    gaunt = 1.1+.34*np.exp(-(5.5-np.log10(T))**2/3)
    freefree = 1.42e-27*gaunt*np.sqrt(T)/ev
    return (down, cooling, inactive, emission,
            collisional_ionization_coefficients(T), excitation, freefree, line_sigma(T))


def c_array(value):
    a = np.asarray(value)
    if a.ndim == 0:
        return format(float(a), ".17g")
    return "{" + ", ".join(c_array(v) for v in a) + "}"


def render():
    sources = sorted(REFERENCE.rglob("*.py"))
    fingerprint = hashlib.sha256(b"".join(p.relative_to(REFERENCE).as_posix().encode()+b"\0"+
        p.read_bytes() for p in sources)).hexdigest()
    temperatures = np.linspace(5000., 20000., 257)
    conversion = project([HEI_BANDS[2][1]], [HEI_BANDS[0][1]], [0])
    out = ["/* Generated by tools/generate_hhe_atomic_table.py; do not edit.",
           " * Frozen reference SHA256: " + fingerprint,
           " * 257 temperatures, order-2 continuum quadrature, grey threshold bands.",
           " * Coefficients are cm^3/s; energy coefficients eV cm^3/s. */",
           "#ifndef PHOTON_HHE_ATOMIC_TABLE_H", "#define PHOTON_HHE_ATOMIC_TABLE_H",
           "#define HHE_TABLE_ROWS 257",
           "#define HHE_TABLE_DT (15000.0 / 256.0)",
           "const double hhe_group_energy_eV[HHE_NGROUPS] = " + c_array(GRID) + ";",
           "const int hhe_group_kind[HHE_NGROUPS] = {" + ", ".join(map(str, KIND)) + "};",
           "const double hhe_group_cross_section_cm2[HHE_NGROUPS][3] = " + c_array(sigma(GRID)) + ";",
           "static const double hhe_conversion_emission[HHE_NGROUPS] = " + c_array(conversion) + ";",
           "static const double hhe_conversion_inactive = " + c_array(21.2-HEI_BANDS[1][1]) + ";",
           "static const hhe_coefficients hhe_atomic_table[HHE_TABLE_ROWS] = {"]
    for temperature in temperatures:
        out.append("  {" + ", ".join(c_array(v) for v in coefficients(temperature)) + "},")
    out += ["};", "#endif", ""]
    return "\n".join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path,
        default=ROOT / "src/physics/photon_hhe_atomic_table.h")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = render()
    if args.check:
        if not args.output.exists() or args.output.read_text() != text:
            raise SystemExit("H/He atomic table differs; regenerate with this script")
        print("H/He atomic table matches the frozen Python reference")
    else:
        args.output.write_text(text)
        print(f"Wrote {args.output}: {len(text)} bytes")


if __name__ == "__main__":
    main()
